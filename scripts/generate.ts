// Generates new practice questions with Claude. Inputs come from the "Generate questions" workflow.
// Usage: npm run generate -- --role data_engineer --category pipelines --difficulty medium --count 5 [--company Grab]
import { aiEnabled, generateQuestions } from "../lib/ai";
import { Store } from "../lib/store";
import { isCategory, isDifficulty, isRole } from "../lib/taxonomy";
import { arg, writeSummary } from "./lib";

(async () => {
  if (!aiEnabled()) {
    console.error("ANTHROPIC_API_KEY is not set (add it as a repository secret).");
    process.exit(1);
  }
  const role = arg("role"), category = arg("category"), difficulty = arg("difficulty");
  if (!isRole(role) || !isCategory(category) || !isDifficulty(difficulty)) {
    console.error("Pass a valid --role, --category and --difficulty.");
    process.exit(1);
  }
  const company = arg("company")?.trim() || null;
  const count = Math.min(10, Math.max(1, Number(arg("count") ?? 5)));
  const store = new Store();
  const avoid = store.bank.questions.filter((q) => q.category === category).map((q) => q.text);
  const qs = await generateQuestions({ role, category, difficulty, company, count, avoid });
  for (const q of qs) {
    store.insert({ ...q, company, answer_by_ai: true, source_type: "ai", attribution: "Generated by Claude", extracted_by: "ai" });
  }
  store.save();
  writeSummary("AI-generated questions", [`${role} · ${category} · ${difficulty}${company ? ` · ${company} style` : ""}`], store.added);
})();
